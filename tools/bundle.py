#!/usr/bin/env python3
"""Package trusted runtime sources; .NET reads UTF-8 paths before entering Lua."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
out = root / "build/plugin/lua/workshop.lua"
out.parent.mkdir(parents=True, exist_ok=True)
parts = ["-- Generated by tools/bundle.py; edit lua/*.lua instead.\n"]
for module in ("json", "workshop"):
    parts += [f'package.preload["{module}"] = function()\n',
              (root / "lua" / f"{module}.lua").read_text(), "\nend\n"]
parts.append((root / "lua/bootstrap.lua").read_text())
out.write_text("".join(parts))
